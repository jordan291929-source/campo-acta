import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import ts from 'typescript';
import assert from 'node:assert/strict';
await mkdir('.qa',{recursive:true});
const path=resolve('.qa/quantities-model.mjs');
await writeFile(path,ts.transpileModule(await readFile('src/model.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {presentationContent,stockAmounts,equivalentContent,packageLabel}=await import(pathToFileURL(path).href);
assert.deepEqual(stockAmounts(10,'UN','Envase x 20 LT',20),{packages:10,content:200,contentUnit:'L'});
assert.deepEqual(stockAmounts(36,'UN','ENVASE X 5 LT',5),{packages:36,content:180,contentUnit:'L'});
assert.deepEqual(stockAmounts(2,'UN','BOLSA X 5 KG',5),{packages:2,content:10,contentUnit:'KG'});
assert.deepEqual(stockAmounts(200,'L','Envase x 20 LT',20),{packages:10,content:200,contentUnit:'L'});
assert.deepEqual(stockAmounts(0,'UN','Envase x 20 L',20),{packages:0,content:0,contentUnit:'L'});
assert.equal(stockAmounts(null,'UN','Envase x 20 L',20),null);
assert.equal(stockAmounts(10,'UN','Sin contenido indicado'),null);
assert.deepEqual(presentationContent('Envase x 0,5 Lt.'),{size:0.5,unit:'L'});
assert.equal(equivalentContent(10,'UN','Envase x 20 L',20),'200 L en total');
assert.equal(packageLabel('BOLSA X 5 KG'),'Bolsa');assert.equal(packageLabel('CILINDRO X 205 LT'),'Cilindro');assert.equal(packageLabel('x 5 L'),'Envase');assert.equal(packageLabel('ENVASE X 5 LT','L'),'L');
const exchangePath=resolve('.qa/quantities-exchange.mjs');
await writeFile(exchangePath,ts.transpileModule((await readFile('src/exchange.ts','utf8')).replace("from './model'","from './quantities-model.mjs'"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {convertPrice}=await import(pathToFileURL(exchangePath).href);
assert.equal(convertPrice(30.2119,'USD','PEN',3.381),102.15);assert.equal(convertPrice(102.15,'PEN','PEN',3.381),102.15);assert.equal(convertPrice(30.2119,'USD','PEN',0),0,'Sin TC no inventa precio');assert.equal(convertPrice(338.1,'PEN','USD',3.381),100);
console.log('OK: envase por presentación (bolsa, cilindro); USD a soles con TC referencial, sin TC el precio queda en cero.');
console.log('OK: 10 envases x20 L = 200 L; litros sin doble conversión; kilos, cero, desconocidos y decimales.');
